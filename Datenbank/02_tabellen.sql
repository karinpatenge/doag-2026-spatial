-- Tabellen des Vortrags „Hänsel und Gretel im Geodatenwald“ mit Metadaten und Spatial Indizes.
-- Ausführen als DOAG_SPATIAL nach pa_geo.pck.
-- Der Spatial Index auf baum entsteht erst in 03_maerchendaten.sql, nach dem Laden der Bäume.

drop table if exists ort purge;
drop table if exists weg purge;
drop table if exists flaeche purge;
drop table if exists baum purge;
drop table if exists land purge;

delete from user_sdo_geom_metadata
  where table_name in (upper('ort'), upper('weg'), upper('flaeche'), upper('baum'), upper('land'));

create table ort (
  ort_id  integer generated by default as identity annotations (description 'Primärschlüssel'),
  name    varchar2(50) not null annotations (description 'Name des Ortes, z. B. Elternhaus oder Kieselstein'),
  nummer  integer annotations (description 'Laufende Nummer der Kieselsteine, 1 am Elternhaus'),
  geo     sdo_geometry not null annotations (description 'Lage als Punkt in ETRS89 / UTM Zone 32N (SRID 25832)'),
  constraint pk_ort   primary key (ort_id),
  constraint uk1_ort  unique (name, nummer),
  constraint chk1_ort check ((name = 'Kieselstein' and nummer is not null)
                         or (name <> 'Kieselstein' and nummer is null))
)
annotations (description 'Punkte im Märchenwald')
;

create table weg (
  weg_id  integer generated by default as identity annotations (description 'Primärschlüssel'),
  name    varchar2(50) not null annotations (description 'Name des Weges, z. B. Irrweg'),
  geo     sdo_geometry not null annotations (description 'Verlauf als Linie in ETRS89 / UTM Zone 32N (SRID 25832)'),
  constraint pk_weg  primary key (weg_id),
  constraint uk1_weg unique (name)
)
annotations (description 'Wege im Märchenwald')
;

create table flaeche (
  flaeche_id  integer generated by default as identity annotations (description 'Primärschlüssel'),
  name        varchar2(50) not null annotations (description 'Name der Fläche, z. B. Wald'),
  geo         sdo_geometry not null annotations (description 'Umriss als Polygon in UTM Zone 32N (SRID 25832)'),
  constraint pk_flaeche  primary key (flaeche_id),
  constraint uk1_flaeche unique (name)
)
annotations (description 'Flächen im Märchenwald')
;

create table baum (
  baum_id  integer generated by default as identity annotations (description 'Primärschlüssel'),
  geo      sdo_geometry not null annotations (description 'Standort als Punkt in ETRS89 / UTM Zone 32N (SRID 25832)'),
  constraint pk_baum primary key (baum_id)
)
annotations (description 'Rund 100 000 zufällig verteilte Bäume im Wald')
;

create table land (
  land_id  integer generated by default as identity annotations (description 'Primärschlüssel'),
  name     varchar2(100) not null annotations (description 'Name des Landes aus Natural Earth'),
  geo      sdo_geometry not null annotations (description 'Grenze als Polygon in WGS 84 (SRID 4326)'),
  constraint pk_land  primary key (land_id),
  constraint uk1_land unique (name)
)
annotations (description 'Ländergrenzen aus Natural Earth 1:110 Mio. für die Weltkarten')
;

insert into user_sdo_geom_metadata (table_name, column_name, diminfo, srid)
  values (upper('ort'), upper('geo'),
          sdo_dim_array(
            sdo_dim_element('x', 600000, 700000, pa_geo.toleranz()),
            sdo_dim_element('y', 5400000, 5500000, pa_geo.toleranz())
          ),
          25832);
insert into user_sdo_geom_metadata (table_name, column_name, diminfo, srid)
  values (upper('weg'), upper('geo'),
          sdo_dim_array(
            sdo_dim_element('x', 600000, 700000, pa_geo.toleranz()),
            sdo_dim_element('y', 5400000, 5500000, pa_geo.toleranz())
          ),
          25832);
insert into user_sdo_geom_metadata (table_name, column_name, diminfo, srid)
  values (upper('flaeche'), upper('geo'),
          sdo_dim_array(
            sdo_dim_element('x', 600000, 700000, pa_geo.toleranz()),
            sdo_dim_element('y', 5400000, 5500000, pa_geo.toleranz())
          ),
          25832);
insert into user_sdo_geom_metadata (table_name, column_name, diminfo, srid)
  values (upper('baum'), upper('geo'),
          sdo_dim_array(
            sdo_dim_element('x', 600000, 700000, pa_geo.toleranz()),
            sdo_dim_element('y', 5400000, 5500000, pa_geo.toleranz())
          ),
          25832);
insert into user_sdo_geom_metadata (table_name, column_name, diminfo, srid)
  values (upper('land'), upper('geo'),
          sdo_dim_array(
            sdo_dim_element('longitude', -180, 180, pa_geo.toleranz()),
            sdo_dim_element('latitude', -90, 90, pa_geo.toleranz())
          ),
          4326);
commit;

create index ids1_ort on ort(geo) indextype is mdsys.spatial_index_v2;
create index ids1_weg on weg(geo) indextype is mdsys.spatial_index_v2;
create index ids1_flaeche on flaeche(geo) indextype is mdsys.spatial_index_v2;
create index ids1_land on land(geo) indextype is mdsys.spatial_index_v2;
